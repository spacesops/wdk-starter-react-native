#!/usr/bin/env node

/**
 * Make @spacesprotocol/react-native-libveritas work on this app:
 * - Avoid double installRustCrate on Metro fast refresh (global guard)
 * - Use TurboModuleRegistry.get instead of getEnforcing (clearer errors)
 * - Fix CallInvokerHolder JNI unpack for React Native 0.80+ (no mHybridData)
 */

const fs = require('fs');
const path = require('path');

const projectRoot = path.join(__dirname, '..');
const packageRoot = path.join(
  projectRoot,
  'node_modules',
  '@spacesprotocol',
  'react-native-libveritas'
);

const PATCH_MARKER = 'spaces-wallet-libveritas-lazy-guard';

const NATIVE_SPEC_NEW = `// Generated by uniffi-bindgen-react-native
import type { TurboModule } from 'react-native';
import { TurboModuleRegistry } from 'react-native';

export interface Spec extends TurboModule {
  installRustCrate(): boolean;
  cleanupRustCrate(): boolean;
}

const nativeModule = TurboModuleRegistry.get<Spec>('ReactNativeLibveritas');

export default nativeModule ?? {
  installRustCrate(): boolean {
    throw new Error(
      '[libveritas] ReactNativeLibveritas native module is not linked. Rebuild the dev client (npm run android / npm run ios).'
    );
  },
  cleanupRustCrate(): boolean {
    return false;
  },
};
`;

const INDEX_TS_NEW = `// Generated by uniffi-bindgen-react-native
import installer from './NativeReactNativeLibveritas';

const RUST_INSTALLED_KEY = '${PATCH_MARKER}:rust-installed';
const UNIFFI_INITIALIZED_KEY = '${PATCH_MARKER}:uniffi-initialized';

function ensureRustInstalled(): void {
  const g = globalThis as typeof globalThis & Record<string, boolean | undefined>;
  if (g[RUST_INSTALLED_KEY]) {
    return;
  }
  const ok = installer.installRustCrate();
  console.log('[libveritas] installRustCrate:', ok);
  g[RUST_INSTALLED_KEY] = true;
}

ensureRustInstalled();

// Export the generated bindings to the app.
export * from './generated/libveritas_uniffi';

// Now import the bindings so we can:
// - intialize them
// - export them as namespaced objects as the default export.
import * as libveritas_uniffi from './generated/libveritas_uniffi';

function ensureUniffiInitialized(): void {
  const g = globalThis as typeof globalThis & Record<string, boolean | undefined>;
  if (g[UNIFFI_INITIALIZED_KEY]) {
    return;
  }
  libveritas_uniffi.default.initialize();
  g[UNIFFI_INITIALIZED_KEY] = true;
}

ensureUniffiInitialized();

// This provides parity with the index.web.ts version of this file.
export async function uniffiInitAsync() {
  // NOOP.
}

export default {
  libveritas_uniffi,
};
`;

const CPP_ADAPTER_MARKER = 'spaces-wallet-libveritas-rn080-callinvoker';

const CPP_ADAPTER_NEW = `// Generated by uniffi-bindgen-react-native
#include <jni.h>
#include <jsi/jsi.h>
#include <ReactCommon/CallInvokerHolder.h>
#include "spacesprotocol-react-native-libveritas.h"

namespace jsi = facebook::jsi;
namespace react = facebook::react;

// Automated testing checks Java_com_spacesprotocol_reactnativelibveritas_ReactNativeLibveritasModule and spacesprotocol_reactnativelibveritas
// by comparing the whole line here.
/*
Java_com_spacesprotocol_reactnativelibveritas_ReactNativeLibveritasModule_nativeMultiply(JNIEnv *env, jclass type, jdouble a, jdouble b) {
    return spacesprotocol_reactnativelibveritas::multiply(a, b);
}
*/

// Installer coming from ReactNativeLibveritasModule
extern "C"
JNIEXPORT jboolean JNICALL
Java_com_spacesprotocol_reactnativelibveritas_ReactNativeLibveritasModule_nativeInstallRustCrate(
    JNIEnv *env,
    jclass type,
    jlong rtPtr,
    jobject callInvokerHolderJavaObj
) {
    // ${CPP_ADAPTER_MARKER}: RN 0.80+ removed CallInvokerHolderImpl.mHybridData; use fbjni.
    using JCallInvokerHolder = facebook::react::CallInvokerHolder;

    auto holderLocal = facebook::jni::make_local(callInvokerHolderJavaObj);
    auto holderRef =
        facebook::jni::static_ref_cast<JCallInvokerHolder::javaobject>(holderLocal);
    auto* holderCxx = holderRef->cthis();
    auto jsCallInvoker = holderCxx->getCallInvoker();
    auto runtime = reinterpret_cast<jsi::Runtime *>(rtPtr);

    return spacesprotocol_reactnativelibveritas::installRustCrate(*runtime, jsCallInvoker);
}

extern "C"
JNIEXPORT jboolean JNICALL
Java_com_spacesprotocol_reactnativelibveritas_ReactNativeLibveritasModule_nativeCleanupRustCrate(JNIEnv *env, jclass type, jlong rtPtr) {
    auto runtime = reinterpret_cast<jsi::Runtime *>(rtPtr);
    return spacesprotocol_reactnativelibveritas::cleanupRustCrate(*runtime);
}
`;

function patchFile(relativePath, nextContents) {
  const filePath = path.join(packageRoot, relativePath);
  if (!fs.existsSync(filePath)) {
    console.warn(`[patch-react-native-libveritas] skip missing ${relativePath}`);
    return false;
  }

  const current = fs.readFileSync(filePath, 'utf8');
  if (current.includes(PATCH_MARKER)) {
    console.log(`[patch-react-native-libveritas] already patched ${relativePath}`);
    return true;
  }

  fs.writeFileSync(filePath, nextContents, 'utf8');
  console.log(`[patch-react-native-libveritas] patched ${relativePath}`);
  return true;
}

function main() {
  if (!fs.existsSync(packageRoot)) {
    console.log('[patch-react-native-libveritas] package not installed, skipping');
    return;
  }

  patchFile('src/NativeReactNativeLibveritas.ts', NATIVE_SPEC_NEW);
  patchFile('src/index.ts', INDEX_TS_NEW);
  patchCppAdapter();
}

function patchCppAdapter() {
  const relativePath = 'android/cpp-adapter.cpp';
  const filePath = path.join(packageRoot, relativePath);
  if (!fs.existsSync(filePath)) {
    console.warn(`[patch-react-native-libveritas] skip missing ${relativePath}`);
    return;
  }

  const current = fs.readFileSync(filePath, 'utf8');
  if (current.includes(CPP_ADAPTER_MARKER)) {
    console.log(`[patch-react-native-libveritas] already patched ${relativePath}`);
    return;
  }

  fs.writeFileSync(filePath, CPP_ADAPTER_NEW, 'utf8');
  console.log(`[patch-react-native-libveritas] patched ${relativePath}`);
}

main();
